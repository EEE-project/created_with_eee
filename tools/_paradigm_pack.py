"""A paradigm pack for an ancient Greek lesson page.

A lesson that shows ancient Greek forms builds their paradigms while its page starts, and a browser needs much longer for that than a desktop Python:
an Odyssey lesson spends a large part of its start on it. The export runs the lesson once here, collects the paradigms that its backends built
(`ancient_greek_backend_eee.export_paradigm_pack`) and puts them into the page as an extra first cell, which hands them to the backends again
(`load_paradigm_pack`). The page then builds none of them. The lesson file on disk stays unchanged.

A pack is valid for the versions of ancient-greek-backend-eee, greek-inflexion-eee, greek-accentuation and inflexion that made it; the library
ignores it for any other versions. So the lesson runs in an environment that `uv` resolves from the lesson's own script header (not in the
environment of this export), and the exported page pins those four packages to the versions of that environment.

Not packed: a lesson that needs fewer than MIN_PARADIGMS paradigms (the pack costs more page size than it saves), a lesson without the ancient
Greek backend, and any lesson for which the run fails (the export goes on without a pack and says why).
"""
import base64
import json
import pathlib
import re
import shutil
import subprocess
import tempfile
import tomllib
import zlib

import _embed_data

MIN_PARADIGMS = 20
RUN_TIMEOUT = 900        # seconds: the first run builds an environment and downloads packages

_SCRIPT_BLOCK = re.compile(r"(?m)^# /// script$\s(?P<content>(^#(| .*)$\s)+)^# ///$")      # PEP 723

_DRIVER = '''\
# /// script
# requires-python = ">=3.12"
# dependencies = {dependencies}
# ///
"""Generated by tools/_paradigm_pack.py: run one lesson once and write the paradigm pack of its backends."""
import importlib.util
import pathlib
import sys

notebook, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
spec = importlib.util.spec_from_file_location("lesson", notebook)
module = importlib.util.module_from_spec(spec)
sys.path.insert(0, str(notebook.parent))
spec.loader.exec_module(module)
module.app.run()
import ancient_greek_backend_eee

if not hasattr(ancient_greek_backend_eee, "export_paradigm_pack"):
    sys.exit("ancient-greek-backend-eee in this environment has no export_paradigm_pack (it needs 2.1.0 or newer)")
out.write_bytes(ancient_greek_backend_eee.export_paradigm_pack())
'''

_CELL = '''\
@app.cell(hide_code=True)
def _():
    # Generated at export (tools/_paradigm_pack.py): the paradigms this lesson builds, built when the page was made.
    import base64 as _b64
    try:
        from ancient_greek_backend_eee import load_paradigm_pack as _load_pack
    except ImportError:
        pass
    else:
        print("paradigm pack:", _load_pack(_b64.b64decode({blob!r})), "paradigms loaded")
    return
'''


def header_dependencies(source: str) -> "list[str]":
    """The `dependencies` of the PEP 723 script header of a notebook."""
    match = _SCRIPT_BLOCK.search(source)
    if match is None:
        return []
    text = "".join(line[2:] if line.startswith("# ") else line[1:] for line in match.group("content").splitlines(keepends=True))
    return list(tomllib.loads(text).get("dependencies", []))


def lesson_copy(notebook: pathlib.Path, root: pathlib.Path, tmp_dir: pathlib.Path) -> pathlib.Path:
    """The tracked files directly in the lesson folder and in its parent folder (the two folders a page sees, see _embed_data), copied into tmp_dir with the same
    relative paths. A run there makes `ensure_file()` download into tmp_dir: the repository stays as it was. Returns the path of the lesson copy."""
    notebook, root = pathlib.Path(notebook).resolve(), pathlib.Path(root).resolve()
    for folder in (notebook.parent, notebook.parent.parent):
        for source in filter(pathlib.Path.is_file, _embed_data.tracked_files(root, folder)):
            target = tmp_dir / source.relative_to(root)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
    return tmp_dir / notebook.relative_to(root)


def make_pack(notebook: pathlib.Path, root: pathlib.Path) -> "tuple[bytes | None, str]":
    """Run the lesson once (see the module text). Returns (the pack or None, a note for the export report; empty for a lesson without the ancient Greek backend)."""
    source = pathlib.Path(notebook).read_text(encoding="utf-8")
    if "ancient_greek_backend_eee" not in source:
        return None, ""
    if shutil.which("uv") is None:
        return None, "no paradigm pack: `uv` is not installed"
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        copy = lesson_copy(notebook, root, work / "lesson")
        driver, out = work / "pack_driver.py", work / "pack.bin"
        driver.write_text(_DRIVER.format(dependencies=json.dumps(header_dependencies(source))), encoding="utf-8")
        try:
            run = subprocess.run(["uv", "run", "--no-project", "--script", str(driver), str(copy), str(out)], capture_output=True, text=True, cwd=work, timeout=RUN_TIMEOUT)
        except subprocess.TimeoutExpired:
            return None, f"no paradigm pack: the run took more than {RUN_TIMEOUT} s"
        if run.returncode:
            return None, "no paradigm pack: " + (run.stderr.strip().splitlines() or ["the run failed"])[-1][:200]
        data = out.read_bytes()
    pack = json.loads(zlib.decompress(data))
    count = sum(len(entry["paradigm"]) for entry in pack["lists"])
    if count < MIN_PARADIGMS:
        return None, f"no paradigm pack: the lesson builds only {count} paradigms"
    return data, f"paradigm pack: {count} paradigms, {len(data) / 1024:.0f} KB, " + ", ".join(f"{name} {version}" for name, version in pack["versions"].items())


def pin(source: str, pack: bytes) -> str:
    """The notebook source with the packages of the pack pinned (==) in its script header, so that the page installs the versions that made the pack."""
    for name, version in json.loads(zlib.decompress(pack))["versions"].items():
        line = f'#     "{name}=={version}",\n'
        existing = re.compile(r'(?m)^#\s+"' + re.escape(name) + r'(?![\w.-])[^"]*",\n')
        if existing.search(source):
            source = existing.sub(line, source, count=1)
        else:
            source = source.replace("# ]\n# ///", line + "# ]\n# ///", 1)
    return source


def add(source: str, pack: bytes, pin_versions: bool = True) -> str:
    """The notebook source with the pack cell (and, unless pin_versions is false, the pinned versions)."""
    if pin_versions:
        source = pin(source, pack)
    return _embed_data.insert_cell(source, _CELL.format(blob=base64.b64encode(pack).decode("ascii")))
